def normalize_dest_id(dest: str) -> str:
    """Normalizes any destination string or compound title into a standard identifier."""
    if not dest:
        return "goa"
    cleaned = dest.lower().split(",")[0].replace("dest-", "").strip()
    alias_map = {
        "kerala": "munnar",
        "munnar": "munnar",
        "goa": "goa",
        "manali": "manali",
        "udaipur": "udaipur",
        "jaipur": "jaipur",
        "delhi": "delhi",
        "varanasi": "varanasi",
        "pune": "pune",
        "mumbai": "mumbai",
        "bombay": "mumbai",
        "hampi": "hampi",
        "agra": "agra",
        "amritsar": "amritsar",
        "shimla": "shimla",
    }
    return alias_map.get(cleaned, cleaned)

