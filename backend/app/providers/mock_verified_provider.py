class DestinationProvider:
    @staticmethod
    def get_destinations() -> List[DestinationModel]:
        return DESTINATIONS_DATA

    @staticmethod
    def get_destination(dest_id: str) -> Optional[DestinationModel]:
        norm = normalize_dest_id(dest_id)
        for d in DESTINATIONS_DATA:
            if d.id.lower() == norm or d.name.lower() == norm:
                return d
        return None

    @staticmethod
    def search_destinations(query: str) -> List[DestinationModel]:
        q = query.lower().strip()
        if not q:
            return DESTINATIONS_DATA
        return [
            d for d in DESTINATIONS_DATA
            if q in d.name.lower() or q in d.state.lower() or any(q in t.lower() for t in d.tags)
        ]

    @staticmethod
    def get_attractions(destination_id: str = "goa", category: Optional[str] = None) -> List[AttractionModel]:
        norm_id = normalize_dest_id(destination_id)

        # 1. Exact destination_id or destination_name match
        results = [
            a for a in ATTRACTIONS_DATA
            if a.destination_id.lower() == norm_id or a.destination_name.lower() == norm_id
        ]

        # 2. Match partial name or description strictly for the same destination
        if not results:
            results = [
                a for a in ATTRACTIONS_DATA
                if norm_id in a.destination_name.lower() or norm_id in a.destination_id.lower()
            ]

        # NEVER return another destination's attractions! If unknown, return empty list!

        if category and category.lower() != "all":
            results = [a for a in results if a.category.lower() == category.lower()]

        return results

    @staticmethod
    def search_attractions(query: str) -> List[AttractionModel]:
        q = query.lower().strip()
        if not q:
            return ATTRACTIONS_DATA[:10]
        return [
            a for a in ATTRACTIONS_DATA
            if q in a.name.lower()
            or q in a.category.lower()
            or q in a.destination_name.lower()
            or q in a.destination_id.lower()
            or any(q in t.lower() for t in a.tags)
            or (a.formatted_address and q in a.formatted_address.lower())
            or (a.description and q in a.description.lower())
        ]
